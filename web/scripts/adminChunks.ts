/**
 * Keeps admin-dashboard code out of the driver PWA's offline precache, by chunk graph
 * rather than by file name.
 *
 * Drivers install the app on their phones and the service worker downloads every
 * precached file (again on each deploy, for files whose hash changed). The dashboard is
 * only used on desktop. Its code enters the bundle through dynamic imports in
 * `src/App.tsx` of `src/screens/admin/AdminApp.tsx` (the classic admin's AdminApp is
 * also recognised, but it is no longer routed), so:
 *
 *   driver files      = everything reachable from the entry chunk, following static and
 *                       dynamic imports, but NOT into an AdminApp chunk
 *   admin-only files  = everything reachable from the AdminApp chunks that is not a
 *                       driver file (plus the CSS those chunks import)
 *
 * `generateBundle` runs before vite-plugin-pwa writes the service worker (closeBundle),
 * so `isAdminOnlyFile` is ready for Workbox's `manifestTransforms` in vite.config.ts.
 * The graph is also written to node_modules/.cache/tmv-web/chunk-graph.json (never
 * deployed) for `npm run check:precache`.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { Plugin, Rollup } from "vite";

const ADMIN_ENTRY = /[\\/]src[\\/]screens[\\/]admin(?:-classic)?[\\/]AdminApp\.tsx$/;
const DEV_ONLY = /[\\/]src[\\/]mocks[\\/]/;

export const CHUNK_GRAPH_REPORT = join("node_modules", ".cache", "tmv-web", "chunk-graph.json");

const adminOnly = new Set<string>();

/** True for a built file (path relative to dist, e.g. "assets/AdminApp-1a2b.js") that only the admin uses. */
export function isAdminOnlyFile(url: string): boolean {
  return adminOnly.has(url.replace(/^\/+/, ""));
}

export function adminChunksPlugin(): Plugin {
  let root = process.cwd();
  return {
    name: "tmv-admin-only-chunks",
    apply: "build",
    configResolved(config) { root = config.root; },
    generateBundle(_options, bundle) {
      adminOnly.clear();
      const chunks = new Map<string, Rollup.OutputChunk>();
      for (const item of Object.values(bundle)) if (item.type === "chunk") chunks.set(item.fileName, item);
      // Match on the modules a chunk contains: Rollup leaves facadeModuleId null for the
      // AdminApp dynamic entry, so the facade cannot be relied on.
      const contains = (chunk: Rollup.OutputChunk, pattern: RegExp) => chunk.moduleIds.some(id => pattern.test(id));

      const walk = (start: string[], follow: (target: Rollup.OutputChunk) => boolean) => {
        const seen = new Set<string>();
        const queue = [...start];
        while (queue.length) {
          const file = queue.pop()!;
          const chunk = chunks.get(file);
          if (!chunk || seen.has(file)) continue;
          seen.add(file);
          queue.push(...chunk.imports);
          for (const target of chunk.dynamicImports) {
            const next = chunks.get(target);
            if (next && follow(next)) queue.push(target);
          }
        }
        return seen;
      };
      const withCss = (files: Set<string>) => {
        const all = new Set(files);
        for (const file of files) for (const css of chunks.get(file)?.viteMetadata?.importedCss ?? []) all.add(css);
        return all;
      };

      const entries = [...chunks.values()].filter(chunk => chunk.isEntry).map(chunk => chunk.fileName);
      const driver = withCss(walk(entries, next => !contains(next, ADMIN_ENTRY) && !contains(next, DEV_ONLY)));
      const adminEntries = [...chunks.values()].filter(chunk => !chunk.isEntry && contains(chunk, ADMIN_ENTRY)).map(chunk => chunk.fileName);
      const admin = withCss(walk(adminEntries, () => true));
      for (const file of admin) if (!driver.has(file)) adminOnly.add(file);

      const report = {
        note: "Generated by scripts/adminChunks.ts during `vite build`. Read by scripts/check-precache.mjs.",
        adminEntryFound: adminEntries.length > 0,
        /** One per routed admin dashboard (Aurora); check-precache expects 1. */
        adminEntryCount: adminEntries.length,
        driverFiles: [...driver].sort(),
        adminOnlyFiles: [...adminOnly].sort()
      };
      const out = join(root, CHUNK_GRAPH_REPORT);
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, JSON.stringify(report, null, 2));
    }
  };
}
